create table if not exists public.products (
  id          bigint generated by default as identity primary key,
  name        text           not null,
  new_price   numeric(10, 2) not null check (new_price >= 0),
  old_price   numeric(10, 2) not null check (old_price >= 0),
  image       text           not null,
  category    text           not null check (category in ('men', 'women', 'kid')),
  date        timestamptz    not null default now(),
  available   boolean        not null default true
);

create index if not exists products_category_idx on public.products (category);

-- Row Level Security: anyone may read products; only the backend (service role key,
-- which bypasses RLS) may insert/update/delete.
alter table public.products enable row level security;

drop policy if exists "Products are publicly readable" on public.products;
create policy "Products are publicly readable"
  on public.products for select
  using (true);


-- Newer Supabase projects don't grant API roles access to tables created in SQL.
-- The backend (service_role) needs full access; the public roles may only read (RLS enforces this too).
grant usage on schema public to anon, authenticated, service_role;
grant select, insert, update, delete on public.products to service_role;
grant usage, select on all sequences in schema public to service_role;
grant select on public.products to anon, authenticated;

-- Public bucket for product images (uploads go through the backend).
insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

